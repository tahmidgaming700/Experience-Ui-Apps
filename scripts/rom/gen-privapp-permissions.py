#!/usr/bin/env python3
"""Generate privapp-permissions-experience.xml from the actual Experience APKs.

LineageOS 18.1 sets ro.control_privapp_permissions=enforce: if a /system/priv-app
package requests a privileged permission that is not allow-listed, system_server
refuses to boot. So the allowlist is derived mechanically from what each privileged
APK requests, intersected with the platform's privileged permissions, instead of
being written by hand.

  gen-privapp-permissions.py --bp rom/vendor/experience/prebuilt/apps/Android.bp \
      --apks <dir with <Module>/<Module>.apk> \
      --platform-manifest frameworks/base/core/res/AndroidManifest.xml [--platform-manifest ...] \
      --aapt2 <path> --out privapp-permissions-experience.xml [--check]

--check compares with the existing --out file and fails if it is out of date.
"""
import argparse
import os
import re
import subprocess
import sys
import xml.etree.ElementTree as ET

ANDROID_NS = "{http://schemas.android.com/apk/res/android}"


def privileged_modules(bp_path):
    """Names of android_app_import modules with privileged: true."""
    text = open(bp_path).read()
    mods = []
    for block in re.findall(r"android_app_import\s*\{(.*?)\n\}", text, re.S):
        name = re.search(r'name:\s*"([^"]+)"', block).group(1)
        if re.search(r"privileged:\s*true", block):
            mods.append(name)
    return mods


def platform_privileged_permissions(manifests):
    perms = {}
    for path in manifests:
        root = ET.parse(path).getroot()
        for p in root.iter("permission"):
            name = p.get(ANDROID_NS + "name")
            level = p.get(ANDROID_NS + "protectionLevel") or ""
            if name:
                perms[name] = level
    return {n for n, lvl in perms.items() if "privileged" in lvl.split("|")}


def requested_permissions(aapt2, apk):
    out = subprocess.run([aapt2, "dump", "permissions", apk], check=True, capture_output=True, text=True).stdout
    pkg = re.search(r"^package: (\S+)", out, re.M).group(1)
    perms = sorted(set(re.findall(r"^uses-permission: name='([^']+)'", out, re.M)))
    return pkg, perms


def render(entries):
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!--",
        "    Experience UI privileged permission allowlist (Android 11).",
        "    GENERATED by scripts/rom/gen-privapp-permissions.py from the Experience APKs",
        "    and the platform's privileged permissions. Do not edit by hand.",
        "-->",
        "<permissions>",
    ]
    for module, pkg, perms in entries:
        lines.append(f'    <!-- {module} -->')
        lines.append(f'    <privapp-permissions package="{pkg}">')
        for p in perms:
            lines.append(f'        <permission name="{p}" />')
        lines.append("    </privapp-permissions>")
    lines.append("</permissions>")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bp", required=True)
    ap.add_argument("--apks", required=True)
    ap.add_argument("--platform-manifest", action="append", required=True)
    ap.add_argument("--aapt2", default="aapt2")
    ap.add_argument("--out", required=True)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    privileged = platform_privileged_permissions(a.platform_manifest)
    if len(privileged) < 100:
        sys.exit(f"only {len(privileged)} privileged permissions found; wrong platform manifest?")
    entries = []
    for module in privileged_modules(a.bp):
        apk = os.path.join(a.apks, module, module + ".apk")
        if not os.path.isfile(apk):
            sys.exit(f"missing {apk}")
        pkg, requested = requested_permissions(a.aapt2, apk)
        entries.append((module, pkg, [p for p in requested if p in privileged]))
    xml = render(entries)
    if a.check:
        current = open(a.out).read() if os.path.exists(a.out) else ""
        if current != xml:
            sys.stderr.write(f"{a.out} is out of date; regenerate it with this script\n")
            sys.exit(1)
        print(f"{a.out} is up to date")
        return
    with open(a.out, "w") as f:
        f.write(xml)
    for module, pkg, perms in entries:
        print(f"{module} ({pkg}): {len(perms)} privileged permissions")


if __name__ == "__main__":
    main()
