#!/usr/bin/env python3
"""Generate the Experience UI accent colour runtime resource overlays.

Each accent provides accent_device_default_light (light theme, M3 tone ~40) and
accent_device_default_dark (dark theme, M3 tone ~80) for the "android" package, in
the category Android 11 uses for accent colours (android.theme.customization.accent_color).
Both tones are checked for WCAG contrast against the light/dark surfaces they sit on.

Usage: gen-accent-overlays.py <vendor/experience/overlay/accents>
"""
import os
import sys

# name: (light accent, dark accent)
PALETTE = {
    "Indigo":   ("#4355B9", "#BAC3FF"),
    "Azure":    ("#00639B", "#94CCFF"),
    "Teal":     ("#006A60", "#53DBC9"),
    "Verdant":  ("#2E6C00", "#8DDA5E"),
    "Amber":    ("#855400", "#FFB951"),
    "Coral":    ("#A73A26", "#FFB4A5"),
    "Rose":     ("#A2335F", "#FFB0C9"),
    "Violet":   ("#7444AA", "#DDB8FF"),
    "Graphite": ("#5C5E67", "#C5C6D0"),
}
LIGHT_SURFACE = "#FBF8FF"
DARK_SURFACE = "#121318"

LICENSE = "<!-- Copyright (C) 2026 The Experience UI Project. Licensed under the Apache License, Version 2.0. -->"


def luminance(hex_color):
    v = int(hex_color.lstrip("#"), 16)
    def ch(c):
        c /= 255.0
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * ch((v >> 16) & 255) + 0.7152 * ch((v >> 8) & 255) + 0.0722 * ch(v & 255)


def contrast(a, b):
    la, lb = luminance(a), luminance(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def main(out):
    bp = [
        "// Experience UI accent colour overlays (runtime RROs, category",
        "// android.theme.customization.accent_color), switchable from Experience Settings.",
        "// Generated by scripts/rom/gen-accent-overlays.py: edit the palette there.",
        "",
    ]
    for name, (light, dark) in PALETTE.items():
        # Accent is used for text, controls and focus: require WCAG AA for UI (3:1) and
        # aim for 4.5:1 so accent-coloured text is readable.
        for colour, surface in ((light, LIGHT_SURFACE), (dark, DARK_SURFACE)):
            ratio = contrast(colour, surface)
            if ratio < 4.5:
                sys.exit(f"{name}: {colour} on {surface} contrast {ratio:.2f} < 4.5")
        module = f"ExperienceAccent{name}"
        pkg = f"com.experience.theme.accent.{name.lower()}"
        d = os.path.join(out, module)
        os.makedirs(os.path.join(d, "res", "values"), exist_ok=True)
        with open(os.path.join(d, "AndroidManifest.xml"), "w") as f:
            f.write(f'''<?xml version="1.0" encoding="utf-8"?>
{LICENSE}
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    package="{pkg}"
    android:versionCode="1"
    android:versionName="1.0">
    <overlay android:targetPackage="android"
        android:category="android.theme.customization.accent_color"
        android:priority="1" />
    <application android:label="@string/accent_name" android:hasCode="false" />
</manifest>
''')
        with open(os.path.join(d, "res", "values", "colors.xml"), "w") as f:
            f.write(f'''<?xml version="1.0" encoding="utf-8"?>
{LICENSE}
<resources>
    <color name="accent_device_default_light">{light}</color>
    <color name="accent_device_default_dark">{dark}</color>
</resources>
''')
        with open(os.path.join(d, "res", "values", "strings.xml"), "w") as f:
            f.write(f'''<?xml version="1.0" encoding="utf-8"?>
{LICENSE}
<resources>
    <string name="accent_name">{name}</string>
</resources>
''')
        bp += [
            "runtime_resource_overlay {",
            f'    name: "{module}",',
            '    sdk_version: "current",',
            "    product_specific: true,",
            "}",
            "",
        ]
    with open(os.path.join(out, "Android.bp"), "w") as f:
        f.write("\n".join(bp))
    print(f"generated {len(PALETTE)} accent overlays in {out}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
